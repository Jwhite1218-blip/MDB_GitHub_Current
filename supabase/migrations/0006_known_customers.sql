-- Run this once against the already-live database (SQL Editor). Safe to
-- re-run -- idempotent create + upsert.
--
-- known_customers is a real, if partial, seed of actual GP customers (name +
-- GP customer number), used by the Prospects workspace's duplicate-check so
-- it stops fabricating "no match" results against fake data. Grows over time
-- as more real GP exports are imported -- doesn't need to be complete to be
-- honest, since the app only ever claims "no match in known records," never
-- "confirmed new."

create table if not exists known_customers (
  customer_number text primary key,
  customer_name text not null,
  source text not null default 'GP export',
  created_at timestamptz not null default now()
);

grant all on public.known_customers to service_role;
grant usage on schema public to service_role;

